// MARK: - Status

struct StatusBanner: View {
    @EnvironmentObject var model: AppModel

    var body: some View {
        VStack(spacing: 0) {
            if model.sessionIsSimulated && model.isRunning {
                Text("SIMULATED DATA — generated by the built-in simulator, not read from a vehicle")
                    .font(.headline)
                    .foregroundStyle(.black)
                    .frame(maxWidth: .infinity)
                    .padding(6)
                    .background(Color.orange)
                    .accessibilityIdentifier("simulatedBanner")
            }
            HStack(spacing: 10) {
                Circle().fill(color).frame(width: 12, height: 12)
                VStack(alignment: .leading, spacing: 2) {
                    Text(title).font(.headline)
                    if let detail { Text(detail).font(.caption).foregroundStyle(.secondary).lineLimit(2) }
                }
                Spacer()
                if let v = model.adapterInfo.voltage {
                    Text("Adapter voltage: \(v)").font(.caption).foregroundStyle(.secondary)
                }
            }
            .padding(10)
            .background(.bar)
        }
    }

    private var age: String {
        guard let t = model.lastDataAt else { return "" }
        return String(format: "%.1f s ago", max(0, model.now.timeIntervalSince(t)) + 0.0)
    }

    private var title: String {
        switch model.phase {
        case .idle: return "Not connected"
        case .stopped: return "Disconnected"
        case .connecting(let n): return "Opening link: \(n)…"
        case .initializingAdapter: return "Link open — waiting for the adapter to reply…"
        case .waitingForVehicle: return "Adapter replied — waiting for the vehicle"
        case .reconnecting(let a, _): return "Connection lost — reconnecting (attempt \(a))"
        case .live(let sim):
            if model.dataIsFresh { return sim ? "SIMULATED — data \(age)" : "LIVE — vehicle data received \(age)" }
            return "No new data \(age) — data shown is stale"
        }
    }

    private var detail: String? {
        switch model.phase {
        case .waitingForVehicle(let a):
            return "Adapter: \(a). No vehicle data yet. Ignition must be ON (engine running for most readings)."
        case .reconnecting(_, let r): return r
        case .live:
            let p = model.adapterInfo.protocolName.map { "Protocol: \($0)" } ?? ""
            return [model.adapterInfo.identity.map { "Adapter: \($0)" }, p].compactMap { $0 }.joined(separator: " · ")
        default: return model.lastMessage
        }
    }

    private var color: Color {
        switch model.phase {
        case .live: return model.dataIsFresh ? (model.sessionIsSimulated ? .orange : .green) : .yellow
        case .reconnecting: return .red
        case .connecting, .initializingAdapter, .waitingForVehicle: return .yellow
        default: return .gray
        }
    }
}

