    }
}

@MainActor
enum ClearConfirmation {
    /// Shows the warning and requires the user to type CLEAR. Only then asks the engine to clear.
    static func ask(_ model: AppModel) {
        guard model.canClearCodes, let (alert, field) = makeAlert(model) else { return }
        let response = alert.runModal()
        guard response == .alertSecondButtonReturn else { return }
        guard field.stringValue == "CLEAR" else {
            let n = NSAlert(); n.messageText = "Codes were not cleared"; n.informativeText = "You need to type CLEAR exactly (capital letters)."
            n.runModal(); return
        }
        model.clearCodesConfirmed()
    }

    static func makeAlert(_ model: AppModel) -> (NSAlert, NSTextField)? {
        guard let r = model.dtcReport else { return nil }
        func list(_ s: DTCReport.Section) -> String {
            if case .codes(let c) = s { return c.isEmpty ? "none" : c.map(\.code).joined(separator: ", ") }
            return "unknown"
        }
        let alert = NSAlert()
        alert.alertStyle = .critical
        alert.messageText = model.sessionIsSimulated ? "Clear SIMULATED trouble codes?" : "Clear trouble codes on your car?"
        alert.informativeText = """
        This will erase:
        • Stored: \(list(r.stored))
        • Pending: \(list(r.pending))

        It also:
        • turns off the check-engine light
        • erases freeze-frame data
        • resets the emissions readiness monitors. The car will fail an inspection until it has been driven enough for them to complete again.

        Clearing doesn't fix anything. If the fault is still there, the codes will come back.

        Turn the engine OFF, leave the ignition ON, and keep the car parked. The app checks this before sending.

        Type CLEAR to continue.
        """
        let field = NSTextField(frame: NSRect(x: 0, y: 0, width: 220, height: 24))
        field.placeholderString = "CLEAR"
        alert.accessoryView = field
        alert.addButton(withTitle: "Cancel")          // default (Return) is Cancel
        let clearButton = alert.addButton(withTitle: "Clear Codes")
        clearButton.hasDestructiveAction = true
        alert.window.initialFirstResponder = field
        return (alert, field)
    }
}
