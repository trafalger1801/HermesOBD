struct GaugeCard: View {
    @EnvironmentObject var model: AppModel
    let def: PIDDefinition

    var body: some View {
        let d = model.display(def)
        let note = model.statusNote(for: def)
        let unsupported = model.pidStatus[def.pid] == .notAdvertised || model.pidStatus[def.pid] == .noResponse
        VStack(alignment: .leading, spacing: 4) {
            HStack {
                Text(def.name).font(.subheadline.weight(.semibold))
                Spacer()
                Text(String(format: "PID %02X", def.pid)).font(.caption2.monospaced()).foregroundStyle(.tertiary)
            }
            HStack(alignment: .firstTextBaseline, spacing: 4) {
                Text(unsupported ? "—" : d.value)
                    .font(.system(size: 34, weight: .medium, design: .rounded).monospacedDigit())
                    .foregroundStyle(model.dataIsFresh && !unsupported ? Color.primary : Color.secondary)
                Text(d.unit).font(.callout).foregroundStyle(.secondary)
            }
            Text(note ?? (model.sessionIsSimulated && model.latest[def.pid] != nil ? "Simulated" : " "))
                .font(.caption)
                .foregroundStyle(model.sessionIsSimulated && note == nil ? Color.orange : Color.secondary)
        }
        .padding(12)
        .frame(maxWidth: .infinity, alignment: .leading)
        .background(RoundedRectangle(cornerRadius: 10).fill(Color(nsColor: .controlBackgroundColor)))
        .overlay(RoundedRectangle(cornerRadius: 10).stroke(model.sessionIsSimulated ? Color.orange.opacity(0.6) : Color.gray.opacity(0.25)))
