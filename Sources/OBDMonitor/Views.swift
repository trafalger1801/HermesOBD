struct DTCView: View {
    @EnvironmentObject var model: AppModel

    var body: some View {
        VStack(alignment: .leading, spacing: 12) {
            HStack {
                Button("Read Trouble Codes") { model.readDTCs() }
                    .disabled(!model.phase.isLive || model.dtcPending)
                if model.dtcPending { ProgressView().controlSize(.small); Text("Reading…").font(.caption) }
                Spacer()
            }
            if !model.phase.isLive {
                Text("Connect and wait for vehicle data before reading codes.").foregroundStyle(.secondary)
            }
            if let r = model.dtcReport {
                if r.simulated {
                    Text("SIMULATED CODES — not from your vehicle").font(.headline).foregroundStyle(.orange)
                }
                HStack(spacing: 16) {
                    Label(r.milOn == nil ? "Check-engine light: unknown" : (r.milOn! ? "Check-engine light: ON" : "Check-engine light: OFF"),
                          systemImage: "engine.combustion")
                        .foregroundStyle(r.milOn == true ? .orange : .primary)
                    if let n = r.reportedCount { Text("ECU reports \(n) stored code(s)").foregroundStyle(.secondary) }
                    Spacer()
                    Text("Read \(r.readAt.formatted(date: .omitted, time: .standard))").font(.caption).foregroundStyle(.secondary)
                }
                ScrollView {
                    VStack(alignment: .leading, spacing: 14) {
                        section("Stored (confirmed) codes — service 03", r.stored)
                        section("Pending codes — service 07", r.pending)
                        section("Permanent codes — service 0A", r.permanent)
                    }
                }
                Text("Descriptions are generic SAE meanings. Ford-specific codes (P1xxx etc.) need a Ford service reference.")
                    .font(.caption).foregroundStyle(.secondary)
            }
            Spacer()
            ClearCodesPanel()
        }
    }

    @ViewBuilder
    private func section(_ title: String, _ s: DTCReport.Section) -> some View {
        VStack(alignment: .leading, spacing: 6) {
            Text(title).font(.headline)
            switch s {
            case .codes(let codes) where codes.isEmpty:
                Text("None reported").foregroundStyle(.secondary)
            case .codes(let codes):
                ForEach(codes) { c in
                    HStack(alignment: .firstTextBaseline) {
                        Text(c.code).font(.body.monospaced().bold()).frame(width: 70, alignment: .leading)
                        Text(c.genericDescription ?? "No description in built-in table — look this code up")
                            .foregroundStyle(c.genericDescription == nil ? .secondary : .primary)
                    }
                }
            case .notSupported(let why): Text(why).foregroundStyle(.secondary)
            case .failed(let why): Text("Could not read: \(why)").foregroundStyle(.red)
            }
        }
    }
}

