                .disabled(model.isRunning)

                Group {
                    switch model.source {
                    case .simulator: simulatorSettings
                    case .ble: bleSettings
                    case .serial: serialSettings
                    case .wifi: wifiSettings
                    }
                }
                .disabled(model.isRunning)

                HStack {
                    if model.isRunning {
                        Button("Disconnect", role: .destructive) { model.disconnect() }
                            .keyboardShortcut("d")
                    } else {
                        Button("Connect") { model.connect() }
                            .keyboardShortcut(.defaultAction)
                    }
                    if model.isRunning && model.sessionIsSimulated {
                        Button("Simulate dropout") { model.simulateDropout() }
                            .help("Cuts the simulated link to test reconnect behaviour")
                    }
                }
                if model.source == .simulator {
                    Toggle("Simulated engine running", isOn: $model.simEngineRunning)
                        .help("Turn off to simulate key ON / engine off (needed to test clearing codes)")
                }

                Divider()
                Picker("Units", selection: $model.units) {
                    Text("US (°F, mph, psi)").tag(UnitSystem.imperial)
                    Text("Metric (°C, km/h, kPa)").tag(UnitSystem.metric)
                }
                .disabled(model.logger != nil)

                Divider()
                Text("This app only reads data, with one opt-in exception: clearing trouble codes (Trouble Codes tab). It cannot run tests, tune, or write to the car's computer.")
                    .font(.caption)
                    .foregroundStyle(.secondary)
            }
            .padding(14)
        }
    }

    private var simulatorSettings: some View {
        VStack(alignment: .leading, spacing: 6) {
            Text("No hardware needed. Every value is clearly labeled SIMULATED.").font(.caption).foregroundStyle(.secondary)
            Toggle("Vehicle responds (ignition ON)", isOn: $model.simVehicleResponds)
            Toggle("Use J1850 PWM format (non-CAN)", isOn: $model.simUseJ1850)
        }
    }

    private var bleSettings: some View {
        VStack(alignment: .leading, spacing: 6) {
            Text(ble.stateDescription).font(.caption).foregroundStyle(ble.state == .poweredOn ? Color.secondary : Color.red)
            HStack {
                Button(ble.isScanning ? "Stop scan" : "Scan") { ble.isScanning ? ble.stopScan() : ble.startScan() }
                    .disabled(ble.state != .poweredOn)
                if ble.isScanning { ProgressView().controlSize(.small) }
            }
            List(ble.devices, selection: Binding(get: { model.selectedBLE?.id }, set: { id in
                model.selectedBLE = ble.devices.first { $0.id == id }
            })) { d in
                HStack {
                    Text(d.name).fontWeight(d.looksLikeOBDAdapter ? .semibold : .regular)
                    if d.looksLikeOBDAdapter {
                        Text("OBD?").font(.caption2.bold()).foregroundStyle(.white)
                            .padding(.horizontal, 4).background(Capsule().fill(Color.accentColor))
                            .help("Looks like an OBD-II adapter (name or advertised service)")
                    }
                    Spacer()
                    Text("\(d.rssi) dBm").font(.caption).foregroundStyle(.secondary)
                }
                .tag(d.id)
            }
            .frame(height: 180)
            Text("Plug the adapter into the car, ignition ON, then scan. The Innova 3210RS appears as \"Dongle\" plus a number. Likely adapters are marked OBD? and listed first. Don't pair it in System Settings, and close RepairSolutions2 on your phone: the adapter accepts one connection at a time.")
                .font(.caption).foregroundStyle(.secondary)
        }
        .onAppear { _ = ble.manager }   // creating the manager triggers the permission prompt
    }

    private var serialSettings: some View {
        VStack(alignment: .leading, spacing: 6) {
            HStack {
                Picker("Port", selection: $model.serialPath) {
                    if model.serialPorts.isEmpty { Text("No ports found").tag("") }
                    ForEach(model.serialPorts, id: \.self) { Text($0).tag($0) }
                }
                Button("↻") { model.refreshSerialPorts() }.help("Refresh port list")
            }
            Text("For Bluetooth Classic adapters: pair it in System Settings › Bluetooth first (PIN is often 1234 or 0000), then pick its /dev/cu.* port.")
                .font(.caption).foregroundStyle(.secondary)
        }
    }

    private var wifiSettings: some View {
        VStack(alignment: .leading, spacing: 6) {
            TextField("Host", text: $model.wifiHost)
            TextField("Port", text: $model.wifiPort)
            Text("Join the adapter's Wi-Fi network first. 192.168.0.10:35000 is common for Wi-Fi ELM327 adapters, but check your adapter's documentation.")
